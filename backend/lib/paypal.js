/**
 * paypal.js — PayPal Invoicing API v2 client (Sandbox)
 *
 * Flow: getAccessToken() -> createInvoice() -> sendInvoice() -> getInvoice()
 * The payer-facing payment link is `detail.metadata.recipient_view_url`.
 *
 * MOCK MODE: when PAYPAL_MOCK=true (or no credentials configured), all calls
 * are simulated so the demo works without a PayPal developer account.
 */

const BASE = 'https://api-m.sandbox.paypal.com';

const isMock = () =>
  process.env.PAYPAL_MOCK === 'true' ||
  !process.env.PAYPAL_CLIENT_ID ||
  !process.env.PAYPAL_CLIENT_SECRET;

function mockId() {
  const s = () => Math.random().toString(36).slice(2, 8).toUpperCase();
  return `INV2-MOCK-${s()}-${s()}`;
}

async function getAccessToken() {
  if (isMock()) return 'MOCK-ACCESS-TOKEN';
  const auth = Buffer.from(
    `${process.env.PAYPAL_CLIENT_ID}:${process.env.PAYPAL_CLIENT_SECRET}`
  ).toString('base64');
  const res = await fetch(`${BASE}/v1/oauth2/token`, {
    method: 'POST',
    headers: {
      'Authorization': `Basic ${auth}`,
      'Content-Type': 'application/x-www-form-urlencoded',
    },
    body: 'grant_type=client_credentials',
  });
  if (!res.ok) {
    const body = await res.text();
    throw new Error(`PayPal OAuth failed (${res.status}): ${body}`);
  }
  const data = await res.json();
  return data.access_token;
}

function buildInvoiceBody({ amount, currency, recipient_email, description }) {
  const value = Number(amount).toFixed(2);
  const itemName = (description || 'Services').slice(0, 120);
  return {
    detail: {
      currency_code: currency,
      note: 'Thank you for your business.',
      memo: description || 'Invoice generated by AI Payment Link Generator',
      payment_term: { term_type: 'DUE_ON_RECEIPT' },
    },
    primary_recipients: [
      { billing_info: { email_address: recipient_email } },
    ],
    items: [
      {
        name: itemName,
        description: description || itemName,
        quantity: '1',
        unit_amount: { currency_code: currency, value },
      },
    ],
  };
}

async function createInvoice(token, payload) {
  if (isMock()) {
    const id = mockId();
    return {
      id,
      status: 'DRAFT',
      detail: {
        currency_code: payload.currency,
        metadata: {
          recipient_view_url: `https://www.sandbox.paypal.com/invoice/p#${id.replace(/-/g, '').slice(4)}`,
        },
      },
      links: [],
    };
  }
  const res = await fetch(`${BASE}/v2/invoicing/invoices`, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${token}`,
      'Content-Type': 'application/json',
      'PayPal-Request-Id': `inv-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
    },
    body: JSON.stringify(buildInvoiceBody(payload)),
  });
  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Create invoice failed (${res.status}): ${body}`);
  }
  return res.json();
}

async function sendInvoice(token, invoiceId) {
  if (isMock()) return { success: true };
  const res = await fetch(`${BASE}/v2/invoicing/invoices/${invoiceId}/send`, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ send_to_recipient: true }),
  });
  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Send invoice failed (${res.status}): ${body}`);
  }
  return { success: true };
}

async function getInvoice(token, invoiceId) {
  if (isMock()) {
    return {
      id: invoiceId,
      status: 'SENT',
      detail: {
        metadata: {
          recipient_view_url: `https://www.sandbox.paypal.com/invoice/p#${invoiceId.replace(/-/g, '').slice(4)}`,
        },
      },
    };
  }
  const res = await fetch(`${BASE}/v2/invoicing/invoices/${invoiceId}`, {
    headers: { 'Authorization': `Bearer ${token}`, 'Content-Type': 'application/json' },
  });
  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Get invoice failed (${res.status}): ${body}`);
  }
  return res.json();
}

/**
 * High-level: create + send an invoice, return the payer payment link.
 */
async function createPaymentLink({ amount, currency, recipient_email, description }) {
  if (!amount || amount <= 0) throw new Error('Invalid amount');
  if (!recipient_email || !/^\S+@\S+\.\S+$/.test(recipient_email)) {
    throw new Error('Valid recipient email is required');
  }
  const token = await getAccessToken();
  const created = await createInvoice(token, { amount, currency, recipient_email, description });
  await sendInvoice(token, created.id);
  const full = await getInvoice(token, created.id);
  const payment_link =
    full?.detail?.metadata?.recipient_view_url ||
    created?.detail?.metadata?.recipient_view_url ||
    null;
  return {
    invoice_id: created.id,
    status: full.status || created.status,
    payment_link,
    amount: Number(amount).toFixed(2),
    currency,
    recipient_email,
    mode: isMock() ? 'mock' : 'live-sandbox',
  };
}

module.exports = { createPaymentLink, getAccessToken, isMock };
